type CertSeed = Omit<
  ProgressCertification,
  "workCompletedValue" | "retentionAmount" | "amountRecommendedForPayment"
>;

function cert(seed: CertSeed): ProgressCertification {
  const calc = progressPayment({
    contractValue: seed.contractValue,
    currentPercentComplete: seed.currentPercentComplete,
    retentionPercentage: seed.retentionPercentage,
    previousPaymentsValue: seed.previousPaymentsValue,
  });
  return { ...seed, ...calc };
}

