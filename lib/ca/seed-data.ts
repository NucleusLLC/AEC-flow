/**
 * Construction Administration — sample data.
 *
 * Single source of demo data, used two ways:
 *   1. As the offline fallback in the repositories (lib/data/ca/*) so the UI
 *      renders while the Supabase database is paused/unreachable.
 *   2. As the input to `prisma db seed` (prisma/seed.ts) once the DB is live.
 *
 * Derived money fields (change-order total, revised contract value, progress
 * payment) are computed here with lib/ca/calc.ts so the seed always agrees with
 * the live calculation.
 */
import { changeOrderTotal, revisedContractValue, progressPayment } from "@/lib/ca/calc";
import type {
  ChangeOrder,
  Rfi,
  CaReport,
  ProgressCertification,
  PunchListItem,
  SiteInstruction,
  Submittal,
  DelayNotice,
  ChangeOrderCosts,
} from "@/lib/ca/types";

type CoSeed = Omit<ChangeOrder, "totalCost" | "revisedContractValue"> & ChangeOrderCosts;

function co(seed: CoSeed): ChangeOrder {
  const totalCost = changeOrderTotal(seed);
  return {
    ...seed,
    totalCost,
    revisedContractValue: revisedContractValue(
      seed.originalContractValue,
      seed.approvedChangeOrdersToDate + (seed.status === "APPROVED" ? totalCost : 0),
    ),
  };
}

